export function areasInGroup(group: GroupId): PracticeArea[] {
  return areas.filter((area) => area.group === group);
}

export function groupOf(area: PracticeArea): PracticeGroup {
  const group = groups.find((g) => g.id === area.group);
  if (!group) throw new Error(`area ${area.slug} names unknown group ${area.group}`);
  return group;
}

export function areaBySlug(slug: string): PracticeArea | undefined {
  return areas.find((area) => area.slug === slug);
}

export function groupAnchor(id: GroupId): string {
  return `group-${id}`;
}
